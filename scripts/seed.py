#!/usr/bin/env python3
"""Generate supabase/seed.sql from docs/curriculum.yaml (tutor.topic) and labs/*/lab.yaml (tutor.lab).

`supabase db reset` loads the generated file. Re-run after editing the curriculum or adding a lab.
Deterministic output; idempotent SQL (`on conflict do update`).

Usage:
  uv run python scripts/seed.py            # write supabase/seed.sql
  uv run python scripts/seed.py --stdout   # print instead of writing
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CURRICULUM = ROOT / "docs" / "curriculum.yaml"
LABS = ROOT / "labs"
SEED = ROOT / "supabase" / "seed.sql"


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def topic_rows() -> list[tuple[str, str, str, int]]:
    phases = yaml.safe_load(CURRICULUM.read_text())["phases"]
    rows = []
    for phase, spec in sorted(phases.items()):
        for i, slug in enumerate(spec["topics"]):
            title = slug.replace("-", " ")
            rows.append((slug, phase, title, i))
    return rows


def lab_specs() -> list[dict]:
    specs = []
    for path in sorted(LABS.glob("*/lab.yaml")):
        spec = yaml.safe_load(path.read_text())
        spec["setup_path"] = str(path.parent.relative_to(ROOT) / "setup.sql")
        specs.append(spec)
    return specs


def render() -> str:
    out = ["-- GENERATED by scripts/seed.py from docs/curriculum.yaml and labs/*/lab.yaml. Do not edit.", ""]
    values = ",\n".join(f"  ({q(s)}, {q(p)}, {q(t)}, {o})" for s, p, t, o in topic_rows())
    out += [
        "insert into tutor.topic (slug, phase, title, ord) values",
        values,
        "on conflict (slug) do update set phase = excluded.phase, title = excluded.title, ord = excluded.ord;",
        "",
    ]
    for lab in lab_specs():
        topics = "array[" + ", ".join(q(t) for t in lab.get("topics", [])) + "]::text[]"
        out += [
            "insert into tutor.lab (slug, phase, title, difficulty, est_minutes, topics, setup_path) values",
            (
                f"  ({q(lab['slug'])}, {q(lab['phase'])}, {q(lab['title'])}, {q(lab.get('difficulty', 'medium'))}, "
                f"{int(lab.get('est_minutes') or 0)}, {topics}, {q(lab['setup_path'])})"
            ),
            (
                "on conflict (slug) do update set phase = excluded.phase, title = excluded.title,"
                " difficulty = excluded.difficulty, est_minutes = excluded.est_minutes,"
                " topics = excluded.topics, setup_path = excluded.setup_path;"
            ),
            "",
        ]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stdout", action="store_true", help="print the SQL instead of writing seed.sql")
    args = ap.parse_args()
    sql = render()
    if args.stdout:
        print(sql)
    else:
        SEED.write_text(sql)
        print(f"wrote {SEED.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
